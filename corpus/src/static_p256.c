/* NIST P-256 curve parameters as big-endian byte strings. Labels: ECC/P-256.
 *
 * This is how a library that keeps field elements as octet strings stores
 * them - which is the layout our signatures carry. See defeat_p256_limbs.c for
 * the same curve stored the other common way, which we miss. */
#include <stdint.h>
#include "_sink.h"

static const uint8_t P256_B[32] = {
0x5a,0xc6,0x35,0xd8,0xaa,0x3a,0x93,0xe7,0xb3,0xeb,0xbd,0x55,0x76,0x98,0x86,0xbc,
0x65,0x1d,0x06,0xb0,0xcc,0x53,0xb0,0xf6,0x3b,0xce,0x3c,0x3e,0x27,0xd2,0x60,0x4b};

static const uint8_t P256_GX[32] = {
0x6b,0x17,0xd1,0xf2,0xe1,0x2c,0x42,0x47,0xf8,0xbc,0xe6,0xe5,0x63,0xa4,0x40,0xf2,
0x77,0x03,0x7d,0x81,0x2d,0xeb,0x33,0xa0,0xf4,0xa1,0x39,0x45,0xd8,0x98,0xc2,0x96};

static const uint8_t P256_N[32] = {
0xff,0xff,0xff,0xff,0x00,0x00,0x00,0x00,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,
0xbc,0xe6,0xfa,0xad,0xa7,0x17,0x9e,0x84,0xf3,0xb9,0xca,0xc2,0xfc,0x63,0x25,0x51};

int main(int argc, char **argv) {
    unsigned offset = (unsigned)(seed_byte(argc) & 31u);
    (void)argv;
    /* Each table is consumed separately and at an offset the compiler cannot
     * know. Folding the three into one precomputed XOR - which is exactly what
     * -O2 did to the first version of this file - would delete all three
     * constants and turn a positive sample into a silent miss. */
    sink(P256_B + offset, 1);
    sink(P256_GX + offset, 1);
    sink(P256_N + offset, 1);
    return 0;
}
